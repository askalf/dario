// The label-sync PR body the template watcher files. It describes the label changes in the diff and
// asserts nothing about a live capture, a comparison or how the PR was produced.

import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

let pass = 0, fail = 0;
function check(name, cond, detail) {
  if (cond) { console.log(`  OK ${name}`); pass++; }
  else      { console.log(`  FAIL ${name}${detail ? ' :: ' + detail : ''}`); fail++; }
}

const wf = readFileSync(join(dirname(fileURLToPath(import.meta.url)), '..', '.github', 'workflows', 'cc-drift-template-watch.yml'), 'utf8');
const start = wf.indexOf('echo "## Template labels follow Claude Code');
const end = wf.indexOf('} > "$pr_body_file"', start);

console.log('\n=== label-sync PR body ===');
check('the label PR body is found in the workflow', start !== -1 && end > start);
const echoes = wf.slice(start, end).split('\n').filter((l) => /^\s*echo /.test(l)).join('\n');
check('states the label fields it moves', echoes.includes('_version') && echoes.includes('_supportedMaxTested') && echoes.includes('user-agent'), echoes);
const bad = /Generated by|\.yml|computeDrift|capture-and-bake|live CC|safe to merge|review gate|required checks|byte/i.exec(echoes);
check('no run narration, comparison claim or safety argument', bad === null, bad && bad[0]);
check('no em dash', !echoes.includes('—'));

console.log(`\n${pass} pass, ${fail} fail`);
process.exit(fail === 0 ? 0 : 1);
